# --- the claim the whole experiment rests on ----------------------------------------------


async def test_the_offline_sweep_makes_the_same_decision_as_the_shipped_store(
    corpus: H1Corpus, vectors: Vectors
) -> None:
    """ "Replaying the admission decision offline" is an equivalence claim, so it is checked.

    The entries go into a real :class:`ResponseCacheStore` with the corpus's own vectors, and
    its ``search(..., limit=1)`` — the method the gateway calls — is asked for the same
    top-1 the sweep computed. The two must agree on **which entry** and on **how similar**,
    for every probe, or the curve describes a gateway nobody runs.
    """
    space = "prompt"
    store = InMemoryResponseCacheStore()
    namespace = CacheNamespace(
        tenant_id="h1", dialect="anthropic", model="claude-sonnet-5", transport="body"
    )
    shared_context = context_hash(namespace, {"messages": []})
    now = datetime.now(UTC)

    for question in corpus.questions:
        await store.put(
            CacheEntry(
                tenant_id=namespace.tenant_id,
                dialect=namespace.dialect,
                model=namespace.model,
                transport=namespace.transport,
                request_hash=question.id,
                context_hash=shared_context,
                body=question.answer_text.encode(),
                content_type="application/json",
                stop_reason="end_turn",
                source_request_id=question.id,
                embedding_model=corpus.embedding_model,
                embedding=vectors[space][question.id],
                probe=question.prompt,
            )
        )

    predicted = {row.probe: row for row in probe_outcomes(corpus, vectors[space])}
    checked = 0
    for question in corpus.questions[:25]:  # a sample: 130 searches over 130 entries is enough
        matches = await store.search(
            namespace,
            embedding=vectors[space][question.id],
            context_hash=shared_context,
            embedding_model=corpus.embedding_model,
            threshold=0.0,
            limit=2,
            when=now,
        )
        # The store has no leave-one-out, so the probe's own entry is match 0 at 1.0 and the
        # sweep's Family-B neighbour is match 1.
        assert matches[0].entry.request_hash == question.id
        outcome = predicted[f"{question.id}#novel"]
        assert outcome.family == FAMILY_B
        assert matches[1].entry.request_hash == outcome.best.entry
        assert matches[1].similarity == pytest.approx(outcome.best.similarity, abs=1e-6)
        checked += 1
    assert checked == 25
