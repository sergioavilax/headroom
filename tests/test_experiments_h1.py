"""H1's machinery, against the committed artifact — no torch, no Backline, no network.

The division Phase 8 rests on is that everything expensive happened once, on a machine
that had what it needed, and committed its output. These tests are the other half: they
prove the committed artifact is internally honest and that the sweep over it computes what
`experiments/PRE_REGISTRATION.md` says it computes.

The load-bearing one is
:func:`test_the_offline_sweep_makes_the_same_decision_as_the_shipped_store`. The whole
experiment is an *offline replay* of the gateway's admission decision, and "offline replay"
is a claim about equivalence. So it is checked against the real
:class:`~headroom.core.cache.ResponseCacheStore` rather than asserted in a docstring.
"""

