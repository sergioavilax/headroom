# --- the artifact is what it says it is ---------------------------------------------------


def test_the_corpus_hash_still_describes_the_corpus() -> None:
    """A hand-edited text without a rebuild fails here.

    Deliberately self-consistency rather than a pinned literal: the corpus is regenerated by
    a documented operator step (the paid paraphrase batch), and a pinned constant would mean
    a red suite between that step and somebody remembering to update it.
    """
    assert stored_hash_matches()


def test_exactly_three_questions_are_excluded_and_the_reason_is_recorded(corpus: H1Corpus) -> None:
    """Amendment A1's exclusion, visible in the artifact rather than only in the document."""
    assert len(corpus.excluded) == 3
    assert all("no T1 answer key" in reason for _, reason in corpus.excluded)
    assert {question_id for question_id, _ in corpus.excluded} == {
        "hand-adversarial-01",
        "hand-adversarial-02",
        "hand-adversarial-03",
    }
    assert len(corpus.questions) == 130


def test_the_equivalence_diagonal_is_true(corpus: H1Corpus) -> None:
    """Ground truth passes its own scorer, or "provably wrong" means nothing (H-061)."""
    for question in corpus.questions:
        assert corpus.equivalent(asked=question.id, served=question.id)


def test_every_probe_names_a_question_that_exists(corpus: H1Corpus) -> None:
    """The provenance *is* the answer key for cache correctness (BUILD_PLAN §P8.H1)."""
    known = {question.id for question in corpus.questions}
    assert all(probe.source in known for probe in corpus.probes)


def test_the_vectors_belong_to_this_corpus_and_are_unit_length(
    corpus: H1Corpus, vectors: Vectors
) -> None:
    for space in SPACES:
        assert len(vectors[space]) == len(corpus.questions) + len(corpus.probes)
        sample = next(iter(vectors[space].values()))
        assert len(sample) == EMBEDDING_DIMENSIONS
        norm = sum(value * value for value in sample) ** 0.5
        assert norm == pytest.approx(1.0, abs=1e-3)


def test_a_vectors_file_from_another_corpus_is_refused(
    corpus: H1Corpus, tmp_path: pathlib.Path
) -> None:
    """Measuring one corpus with another's geometry fails where it is read, not later."""
    payload = read_json(VECTORS_PATH)
    payload["corpus_hash"] = "0" * 64
    stale = tmp_path / "h1_vectors.json"
    stale.write_text(json.dumps(payload), encoding="utf-8")
    with pytest.raises(ValueError, match="was built for corpus"):
        load_vectors(corpus, stale)


# --- the mechanical checks (H-060, and the QA chain's first clause) ------------------------


def test_a_faithful_paraphrase_passes() -> None:
    body = "What is Mariko Chorus's net payable for 2026-02, after recoupment?"
    assert check_paraphrase(
        body=body,
        candidate="After recoupment, what net payable does Mariko Chorus have for 2026-02?",
    ).ok


@pytest.mark.parametrize(
    ("candidate", "expected_failure"),
    [
        ("What is the net payable for 2026-02, after recoupment?", "lost name"),
        ("What is Mariko Chorus's net payable for February 2026, after recoupment?", "lost period"),
        ("What is Mariko Chorus's net payable for 2026-03, after recoupment?", "lost period"),
        ("What is Mariko Chorus's net payable for 2026-02, after recoupment?", "identical"),
        ("Net payable?", "length ratio"),
        (
            "Mariko Chorus, 2026-02, after recoupment\n\nwhat is the net payable?",
            "blank line",
        ),
        (
            "For 2026-02 give Mariko Chorus's net payable after recoupment. ANSWER: $1.32",
            "output protocol",
        ),
    ],
)
def test_a_paraphrase_that_loses_something_is_refused(
    candidate: str, expected_failure: str
) -> None:
    """Over-broad on purpose: a false positive costs a regeneration, a false negative costs
    a probe that quietly asks a different question."""
    body = "What is Mariko Chorus's net payable for 2026-02, after recoupment?"
    result = check_paraphrase(body=body, candidate=candidate)
    assert not result.ok
    assert any(expected_failure in failure for failure in result.failures), result.failures


def test_two_identical_candidates_are_a_batch_level_failure() -> None:
    body = "How many tracks does Kofi & The Arcade have in our catalog as primary artist?"
    same = "In our catalog, how many tracks list Kofi & The Arcade as primary artist?"
    results = check_batch(body=body, candidates=[same, same])
    assert results[0].ok
    assert not results[1].ok
    assert any("duplicate" in failure for failure in results[1].failures)


def test_salient_tokens_keep_identifiers_and_drop_sentence_openers() -> None:
    tokens = salient_tokens("As of 2026-06-30, read FBR-C-00670 for Yuki Takeda's 22% rate.")
    assert "2026-06-30" in tokens["period"]
    assert "FBR-C-00670" in tokens["code"]
    assert {"Yuki", "Takeda"} <= tokens["name"]
    assert "As" not in tokens["name"]  # a stop-word a paraphrase may legitimately drop
    assert "22" in tokens["number"]


# --- rendering ground truth ---------------------------------------------------------------


def test_a_numeric_answer_never_renders_in_exponent_form(corpus: H1Corpus) -> None:
    """Three of Backline's percent keys are stored as `2E+1`, and its own regex reads that
    as **2**. Phase 3's `0E-12` scar, one repo over."""
    assert all("E+" not in question.answer_text for question in corpus.questions)
    assert all("E-" not in question.answer_text for question in corpus.questions)


@pytest.mark.parametrize(
    ("kind", "expected", "rendered"),
    [
        ("money", "1.32", "ANSWER: $1.32"),
        ("percent", "2E+1", "ANSWER: 20%"),
        ("count", 9, "ANSWER: 9"),
        ("bool", "YES", "ANSWER: YES"),
        ("period", "2026-06", "ANSWER: 2026-06"),
        ("value", "QZFBR2000146", "ANSWER: QZFBR2000146"),
        ("set", ["Bea", "Amara"], "ANSWER: Bea; Amara"),
    ],
)
def test_each_answer_kind_renders_in_backlines_own_protocol(
    kind: str, expected: object, rendered: str
) -> None:
    question = SuiteQuestion(
        id="q",
        category="c",
        agent="counsel",
        answer_kind=kind,
        tiers=("t1",),
        body="body",
        tail="tail",
        expected=expected,
        tolerance=None,
    )
    assert render_answer(question) == rendered


def test_every_committed_answer_uses_a_shape_backlines_extractors_read(corpus: H1Corpus) -> None:
    """`ANSWER:` for scalars, `FLAG:` lines for reconciliation, and nothing else."""
    for question in corpus.questions:
        text = question.answer_text
        if question.answer_kind == "flags":
            assert text.startswith("Scan complete:")
            assert "ANSWER:" not in text
        else:
            assert "ANSWER:" in text


# --- the sweep's arithmetic ---------------------------------------------------------------


def test_classification_follows_the_pre_registered_definitions(corpus: H1Corpus) -> None:
    first, second = corpus.questions[0], corpus.questions[1]
    assert classify(corpus, asked=first.id, served=first.id) == OUTCOME_CORRECT
    expected = (
        OUTCOME_BENIGN if corpus.equivalent(asked=first.id, served=second.id) else OUTCOME_SWA
    )
    assert classify(corpus, asked=first.id, served=second.id) == expected


def test_a_benign_collision_is_never_counted_as_correct(corpus: H1Corpus) -> None:
    """H-061: a right answer reached for the wrong reason is luck, not a correct hit."""
    pairs = [
        (asked, served)
        for asked in corpus.questions
        for served in corpus.questions
        if asked.id != served.id and corpus.equivalent(asked=asked.id, served=served.id)
    ]
    assert pairs, "the corpus has no answer ties at all — check the equivalence matrix"
    for asked, served in pairs[:20]:
        assert classify(corpus, asked=asked.id, served=served.id) == OUTCOME_BENIGN


def test_the_grid_is_the_pre_registered_one() -> None:
    assert GRID[0] == 0.7
    assert GRID[-1] == 0.99
    assert len(GRID) == 59
    assert all(round(GRID[index + 1] - GRID[index], 6) == 0.005 for index in range(len(GRID) - 1))


def test_hits_never_increase_as_the_threshold_rises(corpus: H1Corpus, vectors: Vectors) -> None:
    """Top-1 admission makes the curve a step function, so the counts are monotone — which
    is what H-063's "and stays zero above" clause gets for free rather than by luck."""
    result = sweep(corpus, vectors)
    for space in SPACES:
        curve = result["spaces"][space]["combined"]["curve"]
        hits = [point["hits"] for point in curve]
        poison = [point["silent_wrong_answer"] for point in curve]
        assert hits == sorted(hits, reverse=True)
        assert poison == sorted(poison, reverse=True)


def test_the_committed_curve_is_the_one_this_corpus_produces(
    corpus: H1Corpus, vectors: Vectors
) -> None:
    """REPORT.md's numbers are recomputed from the artifact here, on every run.

    Phase 11's doc-pinning discipline, arriving early: a committed result that no longer
    follows from its committed input is the failure mode a published finding has.
    """
    committed = read_json(RESULTS_DIR / "h1_curve.json")
    assert committed["corpus"]["corpus_hash"] == corpus.corpus_hash
    fresh = sweep(corpus, vectors)
    for space in SPACES:
        assert (
            fresh["spaces"][space]["combined"]["summary"]
            == committed["spaces"][space]["combined"]["summary"]
        )
        assert (
            fresh["spaces"][space]["combined"]["tau_zero"]
            == committed["spaces"][space]["combined"]["tau_zero"]
        )


# --- the claim the whole experiment rests on ----------------------------------------------


async def test_the_offline_sweep_makes_the_same_decision_as_the_shipped_store(
    corpus: H1Corpus, vectors: Vectors
) -> None:
    """ "Replaying the admission decision offline" is an equivalence claim, so it is checked.

    The entries go into a real :class:`ResponseCacheStore` with the corpus's own vectors, and
    its ``search(..., limit=1)`` — the method the gateway calls — is asked for the same
    top-1 the sweep computed. The two must agree on **which entry** and on **how similar**,
    for every probe, or the curve describes a gateway nobody runs.
    """
    space = "prompt"
    store = InMemoryResponseCacheStore()
    namespace = CacheNamespace(
        tenant_id="h1", dialect="anthropic", model="claude-sonnet-5", transport="body"
    )
    shared_context = context_hash(namespace, {"messages": []})
    now = datetime.now(UTC)

    for question in corpus.questions:
        await store.put(
            CacheEntry(
                tenant_id=namespace.tenant_id,
                dialect=namespace.dialect,
                model=namespace.model,
                transport=namespace.transport,
                request_hash=question.id,
                context_hash=shared_context,
                body=question.answer_text.encode(),
                content_type="application/json",
                stop_reason="end_turn",
                source_request_id=question.id,
                embedding_model=corpus.embedding_model,
                embedding=vectors[space][question.id],
                probe=question.prompt,
            )
        )

    predicted = {row.probe: row for row in probe_outcomes(corpus, vectors[space])}
    checked = 0
    for question in corpus.questions[:25]:  # a sample: 130 searches over 130 entries is enough
        matches = await store.search(
            namespace,
            embedding=vectors[space][question.id],
            context_hash=shared_context,
            embedding_model=corpus.embedding_model,
            threshold=0.0,
            limit=2,
            when=now,
        )
        # The store has no leave-one-out, so the probe's own entry is match 0 at 1.0 and the
        # sweep's Family-B neighbour is match 1.
        assert matches[0].entry.request_hash == question.id
        outcome = predicted[f"{question.id}#novel"]
        assert outcome.family == FAMILY_B
        assert matches[1].entry.request_hash == outcome.best.entry
        assert matches[1].similarity == pytest.approx(outcome.best.similarity, abs=1e-6)
        checked += 1
    assert checked == 25
