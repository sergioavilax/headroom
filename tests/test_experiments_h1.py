    suite = Suite(
        name="core",
        suite_hash="h",
        world_seed=1,
        questions=(_question("done"), _question("todo")),
        excluded=(),
    )
    batch = Batch(questions={"done": {"body": "body", "paraphrases": ["a", "b", "c"]}})

